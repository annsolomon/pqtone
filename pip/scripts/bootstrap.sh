#!/usr/bin/env bash
# Creates .env with fresh random secrets (once) and renders the Keycloak realm from its template.
set -euo pipefail
cd "$(dirname "$0")/.."

command -v docker >/dev/null 2>&1 || { echo "Docker is required: https://docs.docker.com/get-docker/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required (docker compose ...)" >&2; exit 1; }
docker info >/dev/null 2>&1 || { echo "The Docker daemon is not reachable. Start Docker and retry." >&2; exit 1; }

secret() { openssl rand -hex 24; }

if [ ! -f .env ]; then
  umask 077
  cat > .env <<ENV
# Generated by scripts/bootstrap.sh. Local secrets only; never commit this file.
PIP_PUBLIC_URL=http://localhost:8080
PIP_BIND_ADDR=127.0.0.1
PIP_UID=$(id -u)
PIP_GID=$(id -g)
POSTGRES_PASSWORD=$(secret)
PIP_DB_MIGRATOR_PASSWORD=$(secret)
PIP_DB_APP_PASSWORD=$(secret)
PIP_DB_READ_PASSWORD=$(secret)
PIP_KAFKA_ADMIN_PASSWORD=$(secret)
PIP_KAFKA_EVENTCORE_PASSWORD=$(secret)
PIP_KAFKA_RULES_PASSWORD=$(secret)
PIP_KAFKA_SIM_PASSWORD=$(secret)
KC_ADMIN_PASSWORD=$(secret)
PIP_OIDC_CLIENT_SECRET=$(secret)
PIP_SIM_CLIENT_SECRET=$(secret)
PIP_EDGE_CLIENT_SECRET=$(secret)
PIP_VIEWER_PASSWORD=$(secret)
PIP_OPERATOR_PASSWORD=$(secret)
PIP_REVIEWER_PASSWORD=$(secret)
PIP_ADMIN_PASSWORD=$(secret)
GRAFANA_ADMIN_PASSWORD=$(secret)
ENV
  if grep -qE "^[A-Z_]+=$" .env; then echo "empty secret in .env" >&2; rm .env; exit 1; fi
  echo "created .env with fresh secrets"
fi

set -a
# shellcheck disable=SC1091
. ./.env
set +a

# Keycloak realm sslRequired: external (default, localhost mode) | none (Codespaces URL mode) | all
PIP_KC_SSL_REQUIRED="${PIP_KC_SSL_REQUIRED:-external}"
case "$PIP_KC_SSL_REQUIRED" in
  external|none|all) ;;
  *) echo "PIP_KC_SSL_REQUIRED must be external, none or all (got: $PIP_KC_SSL_REQUIRED)" >&2; exit 1 ;;
esac

mkdir -p deploy/keycloak/generated .work/reports
sed -e "s#__PUBLIC_URL__#${PIP_PUBLIC_URL}#g" \
    -e "s#__KC_SSL_REQUIRED__#${PIP_KC_SSL_REQUIRED}#g" \
    -e "s#__OIDC_CLIENT_SECRET__#${PIP_OIDC_CLIENT_SECRET}#g" \
    -e "s#__SIM_CLIENT_SECRET__#${PIP_SIM_CLIENT_SECRET}#g" \
    -e "s#__EDGE_CLIENT_SECRET__#${PIP_EDGE_CLIENT_SECRET}#g" \
    -e "s#__VIEWER_PASSWORD__#${PIP_VIEWER_PASSWORD}#g" \
    -e "s#__OPERATOR_PASSWORD__#${PIP_OPERATOR_PASSWORD}#g" \
    -e "s#__REVIEWER_PASSWORD__#${PIP_REVIEWER_PASSWORD}#g" \
    -e "s#__ADMIN_PASSWORD__#${PIP_ADMIN_PASSWORD}#g" \
    deploy/keycloak/pip-realm.json.tmpl > deploy/keycloak/generated/pip-realm.json
if grep -qE '__[A-Z_]+__' deploy/keycloak/generated/pip-realm.json; then
  echo "unrendered placeholder in deploy/keycloak/generated/pip-realm.json" >&2; exit 1
fi
chmod 644 deploy/keycloak/generated/pip-realm.json   # read by the keycloak container user

if [ -n "${CODESPACES:-}" ] && [ "${PIP_PUBLIC_URL}" = "http://localhost:8080" ]; then
  echo "note: in GitHub Codespaces, open the console through port forwarding to localhost:8080"
  echo "      (VS Code desktop, or 'gh codespace ports forward 8080:8080' on your machine)."
fi
